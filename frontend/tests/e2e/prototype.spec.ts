import { test, expect, type Page } from '@playwright/test'

test.beforeEach(async ({ request }) => {
  await request.post('http://127.0.0.1:18000/__control', { data: { mode: 'normal' } })
})
async function submit(page: Page) {
  await page.getByRole('button', { name: 'Find Best Payment Route' }).click()
}
async function checkPopup(page: Page, name: RegExp, destination: string) {
  const link = page.getByRole('article', { name: 'Best Payment Route', exact: true }).getByRole('link', { name })
  await expect(link).toHaveAttribute('href', destination)
  await expect(link).toHaveAttribute('target', '_blank')
  await expect(link).toHaveAttribute('rel', 'noopener noreferrer')
  await page.context().route(destination, route => route.fulfill({ contentType: 'text/html', body: '<title>Provider</title>' }))
  const opened = page.waitForEvent('popup')
  await link.click()
  const popup = await opened
  await popup.waitForLoadState()
  expect(popup.url()).toBe(destination)
  expect(await popup.evaluate(() => window.opener === null)).toBe(true)
  await popup.close()
}

test('Swiggy ₹500 uses Spring, displays exact costs, and opens safe voucher and terms links', async ({ page }) => {
  const errors: string[] = []
  const network: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => network.push(r.url()))
  await page.goto('/')
  await page.getByLabel('What are you paying for?').fill("I'm ordering on Swiggy for ₹500")
  const responsePromise = page.waitForResponse('**/api/optimize/query')
  await submit(page)
  const response = await responsePromise
  expect(response.status()).toBe(200)
  expect(response.request().postDataJSON().wallet).toContainEqual({ issuer: 'HDFC', productName: 'HDFC Millennia Credit Card', instrumentType: 'CREDIT_CARD', network: 'VISA' })
  await expect(page.getByTestId('best-pay-now')).toHaveText('₹487.50')
  await expect(page.getByTestId('best-effective')).toHaveText('₹487.50')
  const best = page.getByRole('article', { name: 'Best Payment Route', exact: true })
  await expect(best).toContainText('₹12.50')
  await expect(best).toContainText('Voucher covers purchase')
  await expect(best.locator('.live-steps > li')).toHaveCount(4)
  await expect(page.getByText('Fixture offers', { exact: true })).toBeVisible()
  await checkPopup(page, /Buy Voucher/, 'https://www.gyftr.com/swiggy-money')
  await checkPopup(page, /View Offer Terms/, 'https://www.gyftr.com/swiggy-money')
  expect(network.some(url => /:8000|:18000|\/scrape/.test(url))).toBe(false)
  await page.screenshot({ path: 'test-results/swiggy-' + test.info().project.name + '.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

