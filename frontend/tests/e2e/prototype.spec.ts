test('partial and total acquisition failures preserve direct routes and allow recovery', async ({ page, request }) => {
  await request.post('http://127.0.0.1:18000/__control', { data: { mode: 'partial' } })
  await page.goto('/travel')
  await submit(page)
  await expect(page.getByText('Some providers returned incomplete offers.')).toBeVisible()
  await expect(page.getByTestId('best-pay-now')).toHaveText('₹5,459')
  await request.post('http://127.0.0.1:18000/__control', { data: { mode: 'unavailable' } })
  await page.getByRole('button', { name: 'Refresh offers' }).click()
  await expect(page.getByText('Live offers are unavailable.')).toBeVisible()
  await expect(page.getByTestId('best-pay-now')).toHaveText('₹5,459')
  await request.post('http://127.0.0.1:18000/__control', { data: { mode: 'normal' } })
  await page.getByRole('button', { name: 'Refresh offers' }).click()
  await expect(page.getByText('Live offers are unavailable.')).toHaveCount(0)
  await expect(page.getByTestId('best-pay-now')).toBeVisible()
})

test('API failure, real loading state, cancellation, retry, and wallet persistence', async ({ page }) => {
  await page.goto('/')
  await page.route('**/api/optimize/query', route => route.fulfill({ status: 503, json: { detail: 'Service temporarily unavailable.' } }))
  await submit(page)
  await expect(page.getByRole('alert')).toContainText('Service temporarily unavailable.')
  await page.unroute('**/api/optimize/query')
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/optimize/query', async route => { await gate; await route.continue().catch(() => {}) })
  await submit(page)
  await expect(page.getByRole('status')).toContainText('Checking offers')
  await expect(page.getByRole('button', { name: 'Finding payment routes…' })).toBeDisabled()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  release()
  await page.unroute('**/api/optimize/query')
  await expect(page.getByRole('status')).toHaveCount(0)
  await page.getByLabel('ICICI Credit Card', { exact: true }).uncheck()
  await page.reload()
  await expect(page.getByLabel('ICICI Credit Card', { exact: true })).not.toBeChecked()
  await submit(page)
  await expect(page.getByTestId('best-pay-now')).toHaveText('₹487.50')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Let’s find your next route.' })).toBeVisible()
})
